n1 = input("Digite algo: ")

print("É numérico? ", n1.isnumeric())
print("É alfanumérico? ", n1.isalnum())
print("É só letras? ", n1.isalpha())
print("É decimal? ", n1.isdecimal())
print("Está em minúsculo? ", n1.islower())
print("Está em maiúsculo? ", n1.isupper())
print("Está em formato Título? ", n1.istitle())